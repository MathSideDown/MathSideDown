# pad rows to W
for name,rows in mazes.items():
    new=[]
    for r in rows:
        if len(r)<W:
            r = r[:-1] + (' '*(W-len(r))) + r[-1]
        assert len(r)==W, (name,len(r))
        new.append(r)
    assert len(new)==H, (name,len(new))
    mazes[name]=new
    # ensure S,E present
    flat=''.join(new)
    assert 'S' in flat and 'E' in flat

# build JS block
lines=['const MAZES = {']
for name,rows in mazes.items():
    lines.append('  '+name+':[')
    for r in rows:
        lines.append("    '"+r+"',")
    lines.append('  ],')
lines.append('};')
jsblock='\n'.join(lines)

